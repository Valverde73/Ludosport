    def setUp(self):
        self.js = (BASE_DIR / "app.js").read_text(encoding="utf-8")
        self.css = (BASE_DIR / "styles.css").read_text(encoding="utf-8")

    def test_zero_state_podium_hover_no_neon(self):
        """Adversarial: Zero state podium must strip box-shadow on hover."""
        zero_hover = re.search(r'\[data-podium-state="zero"\]\s+\.podium-card:hover\s*\{([^}]+)\}', self.css)
        self.assertIsNotNone(zero_hover, "Zero state podium hover rule not found")
        self.assertIn("box-shadow: none !important", zero_hover.group(1))
        self.assertIn("transform: none", zero_hover.group(1))

    def test_negative_difference_no_double_minus(self):
        """Adversarial: Negative difference must NOT output double minus like '--5'."""
        ranking_func = self.js.split("renderRanking() {")[1].split("renderMonthlyMedals() {")[0]
        # Diff badge in table
        self.assertIn('diffBadge = `<span class="text-rose-400 font-combat font-bold text-xs">${item.diff}</span>`;', ranking_func)
        # Note that for negative numbers, item.diff is already negative (-5), so output is "-5" not "--5".
        # For positive numbers, it prepends '+': `+${item.diff}`.
        self.assertIn('+${item.diff}', ranking_func)

